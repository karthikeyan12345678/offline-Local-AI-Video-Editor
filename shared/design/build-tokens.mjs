// Generates tokens.css from tokens.json. Usage: node build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'))

const lines = ['/* GENERATED by build-tokens.mjs from tokens.json. Do not edit. */', ':root {']
for (const [k, v] of Object.entries(t.color)) lines.push(`  --color-${k}: ${v};`)
lines.push(`  --font-family: ${t.font.family};`, `  --font-mono: ${t.font.mono};`)
for (const [k, v] of Object.entries(t.font.weight)) lines.push(`  --weight-${k}: ${v};`)
for (const [k, v] of Object.entries(t.text)) {
  lines.push(`  --text-${k}: ${v.size};`, `  --leading-${k}: ${v.line};`)
}
for (const [k, v] of Object.entries(t.space)) lines.push(`  --space-${k}: ${v};`)
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v};`)
lines.push(`  --shadow-sm: ${t.shadow.sm};`, `  --motion-fast: ${t.motion.fast};`, '}', '')

writeFileSync(join(here, 'tokens.css'), lines.join('\n'))
console.log('tokens.css written')
