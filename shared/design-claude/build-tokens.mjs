// Generates tokens.css from tokens.json. Usage: node build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'))
const L = ['/* GENERATED by build-tokens.mjs from tokens.json. Do not edit. */', ':root {', '  color-scheme: dark;']
for (const [k, v] of Object.entries(t.color)) L.push(`  --color-${k}: ${v};`)
for (const [k, v] of Object.entries(t.overlay)) L.push(`  --overlay-${k}: ${v};`)
L.push(`  --font-family: ${t.font.family};`, `  --font-serif: ${t.font.serif};`, `  --font-mono: ${t.font.mono};`)
for (const [k, v] of Object.entries(t.font.weight)) L.push(`  --weight-${k}: ${v};`)
for (const [k, v] of Object.entries(t.text)) L.push(`  --text-${k}: ${v.size};`, `  --leading-${k}: ${v.line};`)
for (const [k, v] of Object.entries(t.space)) L.push(`  --space-${k}: ${v};`)
for (const [k, v] of Object.entries(t.radius)) L.push(`  --radius-${k}: ${v};`)
L.push(`  --shadow-raised: ${t.shadow.raised};`, `  --motion-fast: ${t.motion.fast};`, `  --motion-base: ${t.motion.base};`, '}', '')
writeFileSync(join(here, 'tokens.css'), L.join('\n'))
console.log('tokens.css written')
